import assert from "node:assert/strict";
import fs from "node:fs";
const read=p=>fs.readFileSync(new URL(`../${p}`,import.meta.url),"utf8");
const html=read("index.html"),boot=read("js/boot-check.js"),bundle=read("js/app.bundle.js"),sw=read("sw.js");
assert.match(html,/<script defer src="\.\/js\/app\.bundle\.js"><\/script>/);
assert.doesNotMatch(html,/script type="module"/);
assert.doesNotMatch(html,/src="\.\/js\/app\.js"/);
assert.match(html,/worker-src 'self' blob:/);
assert.match(boot,/fetch\("\.\/js\/app\.bundle\.js"/);
assert.match(boot,/5000/);
assert.match(bundle,/ENCODER_WORKER_SOURCE/);
assert.match(bundle,/new Blob\(\[ENCODER_WORKER_SOURCE\]/);
assert.match(bundle,/new Worker\(workerURL\)/);
assert.doesNotMatch(bundle,/import\.meta/);
assert.doesNotMatch(bundle,/type:\s*["']module["']/);
assert.match(bundle,/window\.__AUDIO_MP3_APP_READY__=true/);
assert.match(sw,/chopper-native-mp3-v1-cache-4-picker-id-hotfix/);
assert.match(sw,/\.\/js\/app\.bundle\.js/);
assert.doesNotMatch(sw,/native-audio-decoder\.js|encoder-worker\.js|analysis-window\.js/);
assert.match(sw,/e\.request\.mode==="navigate"/);
assert.match(sw,/cache:"no-store"/);
console.log("PASS NativeMP3Converter V1.0.3 classic-bundle boot/cache contract");
